-- ── 던전 약칭 한글화 ──────────────────────────────────────────────────
--  왜 필요한가
--    던전 아이콘 밑에 붙는 짧은 이름(약칭)은 자료(EXDB)에 **중국어와 영어만**
--    들어 있다. EXBoss 의 던전(쫄) 페이지는 "영어가 아니면 중국어 약칭" 으로
--    처리해서, 한글 클라이언트에서는 글꼴에 없는 한자가 네모(□□)로 나온다.
--    (같은 함수가 던전(보스) 페이지에는 언어 분기가 있어 그쪽은 멀쩡하다)
--
--  ★ 자료(zhCNShort)는 절대 고치지 않는다 - 한 번 해 봤다가 되돌린 길이다.
--    그 값을 읽는 다른 모듈까지 바뀐다. 특히 ExM+Info.MythicIcon 은
--    "저장된 이름 == 기본값(zhCNShort)" 인지 비교해 현지화 이름으로 갈아 끼우는데,
--    기준이 달라지면 비교가 어긋나 저장된 중국어가 그대로 화면에 남는다.
--
--  그래서 화면 글자만 바꾼다
--    · **EXBoss 창 안에서만** 훑는다(전역 이름 ExwindUnifiedPanelFrame).
--      창 밖은 쳐다보지 않으므로 다른 애드온에 영향이 없다.
--    · 글자가 표의 중국어 약칭과 **통째로 같을 때만** 바꾼다(부분 일치 금지 -
--      다른 글에 섞인 한자를 건드리지 않기 위해).
--    · 애드온이 다시 그리면 지워지므로, 창이 열려 있는 동안만 0.5초마다 확인한다.
--    · 저장 자료(SavedVariables)는 건드리지 않는다.
if GetLocale() == "koKR" then
