        ["诸王"] = "왕안",   -- 왕들의 안식처
        ["神庙"] = "세스랄",     -- 세스랄리스 사원
        ["红玉"] = "루비",     -- 루비 생명의 웅덩이
        ["密谋"] = "골목",     -- 죽음의 골목
        ["洞穴"] = "날로라크",     -- 날로라크의 소굴
        ["夺目"] = "골짜기",   -- 눈부신 골짜기
        ["洞窟"] = "동굴",     -- 마이사라 동굴
        ["节点"] = "제나스",   -- 공결탑 제나스
        ["虚空"] = "투기장",   -- 공허흉터 투기장
        ["毒牙"] = "송곳니",     -- 송곳니의 제단
    }
    local ROOTS = { "ExwindUnifiedPanelFrame", "ExwindToolsMainFrame" }
    local MAX_DEPTH = 10

    local function Sweep(frame, depth)
        if not frame or depth > MAX_DEPTH then return end
        local ok, regions = pcall(function() return { frame:GetRegions() } end)
        if ok then
            for _, r in ipairs(regions) do
                if r and r.GetObjectType and r:GetObjectType() == "FontString" then
                    local text = r:GetText()
                    local ko = text and SHORT[text]
                    if ko then pcall(r.SetText, r, ko) end
                end
            end
        end
        local ok2, kids = pcall(function() return { frame:GetChildren() } end)
        if ok2 then
            for _, kid in ipairs(kids) do Sweep(kid, depth + 1) end
        end
    end

    local elapsed = 0
    local watcher = CreateFrame("Frame")
    watcher:SetScript("OnUpdate", function(_, dt)
        elapsed = elapsed + dt
        if elapsed < 0.5 then return end
        elapsed = 0
        for _, name in ipairs(ROOTS) do
            local f = _G[name]
            if f and f.IsShown and f:IsShown() then Sweep(f, 0) end
        end
    end)
end
